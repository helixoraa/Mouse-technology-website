import fs from 'node:fs';
import { DEFAULT_DESCRIPTION, DEFAULT_TITLE, FALLBACK_PAGE_TITLES } from '../src/lib/seo-defaults';
import { PUBLIC_ROUTES, type PublicPage } from '../src/lib/routes';

/**
 * Build-time page titles and descriptions from the CMS (SiteSettings.seo, edited in Admin -> Settings -> SEO).
 * build/seo-plugin.ts writes them into each page's HTML, so crawlers and link-preview bots (no JavaScript) see
 * the page's own title and description. <Seo> keeps updating them in the browser after client-side navigation.
 *
 * Safety: one read-only query (SELECT inside a READ ONLY transaction). Nothing is ever written. If DATABASE_URL is
 * missing or the database can't be reached, the build continues with the fallbacks below and logs a warning.
 */

export type PageMeta = { title: string; description: string };
export type PageMetaResult = { source: 'cms' | 'snapshot' | 'fallback'; pages: Record<PublicPage, PageMeta>; warning?: string };

type SeoEntry = { title?: unknown; description?: unknown };
type SeoJson = { default?: SeoEntry; pages?: Record<string, SeoEntry | undefined> };

const text = (v: unknown) => (typeof v === 'string' ? v.trim() : '');
const asSeo = (v: unknown): SeoJson => (v && typeof v === 'object' ? (v as SeoJson) : {});

/** Same order as GET /api/pages/:page + <Seo>: the page's own value, then the CMS site default, then seo-defaults.ts. */
export function resolvePageMeta(seo: unknown): Record<PublicPage, PageMeta> {
  const s = asSeo(seo);
  const entries = PUBLIC_ROUTES.map(({ page }) => {
    const p = s.pages?.[page] ?? {};
    return [
      page,
      {
        title: text(p.title) || text(s.default?.title) || DEFAULT_TITLE,
        description: text(p.description) || text(s.default?.description) || DEFAULT_DESCRIPTION,
      },
    ] as const;
  });
  return Object.fromEntries(entries) as Record<PublicPage, PageMeta>;
}

/** Used when the CMS can't be read: a distinct, factual title per page and the site-wide description. */
export function fallbackPageMeta(): Record<PublicPage, PageMeta> {
  const entries = PUBLIC_ROUTES.map(({ page }) => [page, { title: FALLBACK_PAGE_TITLES[page], description: DEFAULT_DESCRIPTION }] as const);
  return Object.fromEntries(entries) as Record<PublicPage, PageMeta>;
}

type ReadOnlyPrisma = {
  $transaction(queries: unknown[]): Promise<unknown[]>;
  $executeRawUnsafe(sql: string): unknown;
  $queryRawUnsafe(sql: string): unknown;
  $disconnect(): Promise<void>;
};
type PrismaModule = { PrismaClient: new (options: { datasources: { db: { url: string } } }) => ReadOnlyPrisma };

const timeout = (ms: number, what: string) =>
  new Promise<never>((_, reject) => {
    setTimeout(() => reject(new Error(`${what} timed out after ${ms / 1000}s`)), ms).unref();
  });

/** SELECT SiteSettings.seo in a READ ONLY transaction (Postgres rejects any write in it). */
export async function readCmsSeo(databaseUrl: string, timeoutMs = 20_000): Promise<unknown> {
  // Resolved at build time from the workspace root (generated by `npm run db:generate -w server`); kept out of the
  // client's dependencies and types on purpose.
  const specifier = '@prisma/client';
  const { PrismaClient } = (await import(/* @vite-ignore */ specifier)) as PrismaModule;
  const prisma = new PrismaClient({ datasources: { db: { url: databaseUrl } } });
  try {
    const [, rows] = await Promise.race([
      prisma.$transaction([
        prisma.$executeRawUnsafe('SET TRANSACTION READ ONLY'),
        prisma.$queryRawUnsafe('SELECT "seo" FROM "SiteSettings" WHERE "id" = 1'),
      ]),
      timeout(timeoutMs, 'Database read'),
    ]);
    const row = (rows as { seo?: unknown }[])[0];
    if (!row) throw new Error('SiteSettings row 1 not found (database not seeded?)');
    return row.seo;
  } finally {
    await Promise.race([prisma.$disconnect().catch(() => undefined), new Promise((r) => setTimeout(r, 2_000).unref())]);
  }
}

/** Never throws: any problem becomes a fallback result with a warning for the build log. */
export async function loadPageMeta(databaseUrl: string | undefined): Promise<PageMetaResult> {
  if (!databaseUrl) {
    return {
      source: 'fallback',
      pages: fallbackPageMeta(),
      warning: 'DATABASE_URL is not set, so page titles come from src/lib/seo-defaults.ts',
    };
  }
  try {
    return { source: 'cms', pages: resolvePageMeta(await readCmsSeo(databaseUrl)) };
  } catch (err) {
    const reason = (err instanceof Error ? err.message : String(err)).split('\n').filter(Boolean).slice(-1)[0] ?? 'unknown error';
    return {
      source: 'fallback',
      pages: fallbackPageMeta(),
      warning: `could not read page titles from the database (${reason.slice(0, 300)}), so they come from src/lib/seo-defaults.ts`,
    };
  }
}

/** Static version: the titles come from the snapshot's SiteSettings.seo (src/content/static-content.json), no database. */
export function loadSnapshotPageMeta(snapshotFile: string): PageMetaResult {
  const { seo } = JSON.parse(fs.readFileSync(snapshotFile, 'utf8')) as { seo?: unknown };
  if (!seo) throw new Error(`${snapshotFile} has no "seo" entry`);
  return { source: 'snapshot', pages: resolvePageMeta(seo) };
}

const escapeHtml = (s: string) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const META_TAGS: [RegExp, (m: PageMeta) => string][] = [
  [/<title>[^<]*<\/title>/, (m) => `<title>${escapeHtml(m.title)}</title>`],
  [/<meta name="description" content="[^"]*" \/>/, (m) => `<meta name="description" content="${escapeHtml(m.description)}" />`],
  [/<meta property="og:title" content="[^"]*" \/>/, (m) => `<meta property="og:title" content="${escapeHtml(m.title)}" />`],
  [
    /<meta property="og:description" content="[^"]*" \/>/,
    (m) => `<meta property="og:description" content="${escapeHtml(m.description)}" />`,
  ],
  [/<meta name="twitter:title" content="[^"]*" \/>/, (m) => `<meta name="twitter:title" content="${escapeHtml(m.title)}" />`],
  [
    /<meta name="twitter:description" content="[^"]*" \/>/,
    (m) => `<meta name="twitter:description" content="${escapeHtml(m.description)}" />`,
  ],
];

/** Write one page's title and description into the HTML: <title>, description, og:title/description, twitter:title/description. */
export function applyPageMeta(html: string, meta: PageMeta): string {
  return META_TAGS.reduce((out, [pattern, tag]) => {
    if (!pattern.test(out)) throw new Error(`maouaj-seo: index.html is missing a tag matching ${pattern}`);
    return out.replace(pattern, () => tag(meta));
  }, html);
}
